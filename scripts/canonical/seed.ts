/**
 * The canonical command-driven seed — DB-08 §1 … §3, at **t₀**.
 *
 * Everything a command owns is built by that command: organizations, team
 * memberships, products, opening balances, the partner catalog, the connection
 * and the mapping. That is DB-08 §5's whole point — the seed itself proves that
 * `org.create`, `product.create` and `stock.recordOpeningBalance` work, that
 * every movement has a receipt, and that the ledger reconciles before a single
 * test runs.
 *
 * **Rerun safety comes from the system's own mechanism, not from a flag.** Every
 * idempotent command carries a stable {@link seedOperationId}, so a second run
 * reads the `commandReceipt`, returns the stored result and writes nothing
 * (`INV-06`). The few surfaces a **client** writes directly in production —
 * categories, the second store room, private partners, purchase-order drafts and
 * their lines — are written here only when absent, so a rerun cannot reset an
 * order that has since moved on.
 */

export interface SeedResult {
  readonly buyerOrgId: string;
  readonly supplierOrgId: string;
  readonly buyerWarehouses: { readonly main: string; readonly cold: string };
  readonly supplierWarehouseId: string;
  readonly productIds: ReadonlyMap<string, string>;
  readonly supplierProductIds: ReadonlyMap<string, string>;
  readonly connectionId: string;
  readonly catalogItemIds: ReadonlyMap<string, string>;
  readonly mappingId: string;
  readonly privatePartnerId: string;
  readonly uids: {
    readonly buyerOwner: string;
    readonly buyerInventory: string;
    readonly buyerProcurement: string;
    readonly buyerStorekeeper: string;
    readonly supplierOwner: string;
  };
}

