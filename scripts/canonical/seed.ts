async function createIfAbsent(
  ref: DocumentReference,
  data: Record<string, unknown>,
): Promise<void> {
  if ((await ref.get()).exists) return;
  await ref.set(data);
}

/**
 * The organization id is server-generated by `org.create`, so a rerun resolves
 * it from the **public directory** rather than assuming it. The handle
 * reservation would refuse a second create anyway; resolving first turns that
 * into a no-op instead of an error.
 */
interface OrganizationSpec {
  readonly handle: string;
  readonly name: string;
  readonly industry: string;
  readonly country: string;
  readonly currency: string;
  readonly timezone: string;
}

async function ensureOrganization(
  db: Firestore,
  spec: OrganizationSpec,
  owner: { uid: string; email: string },
  slot: number,
): Promise<{ orgId: string; warehouseId: string }> {
  const directory = await db.doc(paths.organizationDirectory(spec.handle)).get();
  if (directory.exists) {
    const orgId = directory.get('organizationId') as string;
    const settings = await db.doc(paths.settings(orgId)).get();
    return { orgId, warehouseId: settings.get('defaultWarehouseId') as string };
  }
  const result = await runCommand(
    orgCreate,
    {
      uid: owner.uid,
      email: owner.email,
      orgId: spec.handle,
      operationId: seedOperationId(slot),
      payload: {
        name: spec.name,
        handle: spec.handle,
        industry: spec.industry,
        country: spec.country,
        currency: spec.currency,
        timezone: spec.timezone,
      },
    },
    db,
  );
  return {
    orgId: result.organizationId as string,
    warehouseId: result.warehouseId as string,
  };
}

/** Categories are a `SAFE_DIRECT_CLIENT_WRITE` surface — no command owns them. */
async function ensureCategories(db: Firestore, orgId: string, actorUid: string): Promise<void> {
  for (const [categoryId, name] of CATEGORIES) {
    await createIfAbsent(db.doc(paths.category(orgId, categoryId)), {
      categoryId,
      name,
      status: 'ACTIVE',
      createdAt: CLOCK.t0,
      createdBy: actorUid,
      updatedAt: CLOCK.t0,
      updatedBy: actorUid,
    });
  }
}

/**
 * `org.create` makes the first store room (`Main Store`, the default). The
 * second is a client write: the catalog has `warehouse.archive`, `restore` and
 * `setDefault`, and no `warehouse.create`.
 */
async function ensureColdRoom(db: Firestore, orgId: string, actorUid: string): Promise<string> {
  await createIfAbsent(db.doc(paths.warehouse(orgId, COLD_ROOM_ID)), {
    warehouseId: COLD_ROOM_ID,
    name: 'Cold Room',
    type: 'REFRIGERATED',
    status: 'ACTIVE',
    createdAt: CLOCK.t0,
    createdBy: actorUid,
    updatedAt: CLOCK.t0,
    updatedBy: actorUid,
  });
  return COLD_ROOM_ID;
}

/** The full seven-role team, through the real invitation → acceptance path. */
async function ensureTeam(db: Firestore, orgId: string, ownerUid: string): Promise<void> {
  for (const [index, member] of TEAM.entries()) {
    if (member.role === 'OWNER') continue;
    const existing = await db.doc(paths.member(orgId, member.uid)).get();
    if (existing.exists && existing.get('status') === 'ACTIVE') continue;

    const invitation = await runCommand(
      teamCreateInvitation,
      {
        uid: ownerUid,
        orgId,
        operationId: seedOperationId(SLOT.invitation + index),
        payload: { email: member.email, role: member.role },
      },
      db,
    );
    await runCommand(
      teamAcceptInvitation,
      {
        uid: member.uid,
        email: member.email,
        orgId,
        operationId: seedOperationId(SLOT.acceptance + index),
        payload: { token: invitation.token as string },
      },
      db,
    );
    await db.doc(paths.member(orgId, member.uid)).update({ displayName: member.displayName });
  }
}

/** `product.create` generates the id; a rerun resolves it from `productSkuIndex`. */
async function ensureProduct(
  db: Firestore,
  orgId: string,
  actorUid: string,
  slot: number,
  payload: Record<string, unknown>,
): Promise<string> {
  const sku = payload.internalSku as string;
  const index = await db.doc(paths.productSkuIndex(orgId, sku)).get();
  if (index.exists) return index.get('productId') as string;
  const result = await runCommand(
    productCreate,
    { uid: actorUid, orgId, operationId: seedOperationId(slot), payload },
    db,
  );
  return result.productId as string;
}

export async function seedCanonical(context: SeedContext): Promise<SeedResult> {
  const { db } = context;
  const owner = TEAM.find((member) => member.role === 'OWNER');
  const inventory = TEAM.find((member) => member.role === 'INVENTORY_MANAGER');
  const procurement = TEAM.find((member) => member.role === 'PROCUREMENT_MANAGER');
  const storekeeper = TEAM.find((member) => member.role === 'STOREKEEPER');
  if (!owner || !inventory || !procurement || !storekeeper) {
    throw new Error('The canonical team fixture is incomplete');
  }

  // ── 1 · the two organizations ────────────────────────────────────────────
  const buyer = await ensureOrganization(db, BUYER, owner, SLOT.buyerOrg);
  const supplier = await ensureOrganization(db, SUPPLIER, SUPPLIER_OWNER, SLOT.supplierOrg);

  await ensureCategories(db, buyer.orgId, owner.uid);
  await ensureCategories(db, supplier.orgId, SUPPLIER_OWNER.uid);
  const coldRoomId = await ensureColdRoom(db, buyer.orgId, owner.uid);
  await ensureTeam(db, buyer.orgId, owner.uid);

  // ── 2 · Grand Ocean's twelve products and their opening balances ─────────
  const productIds = new Map<string, string>();
  for (const [index, product] of GRAND_PRODUCTS.entries()) {
    const minimumStockMilli = product.minimum * 1000;
    const id = await ensureProduct(db, buyer.orgId, inventory.uid, SLOT.buyerProduct + index, {
      internalSku: product.sku,
      name: product.name,
      categoryId: product.categoryId,
      baseUnit: product.unit,
      purchaseCostMinor: product.costMinor,
      currency: 'LKR',
      minimumStockMilli,
      reorderTargetMilli: Math.max(minimumStockMilli, minimumStockMilli * 2),
    });
    productIds.set(product.sku, id);

    // Cooking Oil is seeded at **zero** and still gets its movement: a product
    // with no movement and a product at zero are different facts, and the
    // out-of-stock KPI must be provable from the ledger (DB-08 §2).
    await runCommand(
      stockRecordOpeningBalance,
      {
        uid: inventory.uid,
        orgId: buyer.orgId,
        operationId: seedOperationId(SLOT.buyerOpening + index),
        payload: {
          productId: id,
          warehouseId: product.warehouseId === 'cold-room' ? coldRoomId : buyer.warehouseId,
          quantityMilli: product.opening * 1000,
          effectiveAt: CLOCK.t0,
        },
      },
      db,
    );
  }

  // ── 3 · Fresh Foods' two products, balances and partner catalog ──────────
  const supplierProductIds = new Map<string, string>();
  const catalogItemIds = new Map<string, string>();
  for (const [index, product] of SUPPLIER_PRODUCTS.entries()) {
    const id = await ensureProduct(
      db,
      supplier.orgId,
      SUPPLIER_OWNER.uid,
      SLOT.supplierProduct + index,
      {
        internalSku: product.sku,
        name: product.name,
        categoryId: product.categoryId,
        baseUnit: product.unit,
        purchaseCostMinor: 0,
        currency: 'LKR',
        minimumStockMilli: 0,
        reorderTargetMilli: 0,
      },
    );
    supplierProductIds.set(product.sku, id);

    await runCommand(
      stockRecordOpeningBalance,
      {
        uid: SUPPLIER_OWNER.uid,
        orgId: supplier.orgId,
        operationId: seedOperationId(SLOT.supplierOpening + index),
        payload: {
          productId: id,
          warehouseId: supplier.warehouseId,
          quantityMilli: product.opening * 1000,
          effectiveAt: CLOCK.t0,
        },
      },
      db,
    );

    // `partnerCatalog.publish` is NOT idempotent (DB-06 §1), so the rerun guard
    // is the frozen `partnerPublished` flag the command itself maintains.
    const productDoc = await db.doc(paths.product(supplier.orgId, id)).get();
    if (productDoc.get('partnerPublished') !== true) {
      const item = await runCommand(
        partnerCatalogPublish,
        {
          uid: SUPPLIER_OWNER.uid,
          orgId: supplier.orgId,
          payload: {
            sourceProductId: id,
            partnerSku: product.partnerSku,
            displayName: product.name,
            // INV-17 — the order unit IS the product's base unit.
            orderUnit: product.unit,
            packDescription: product.packDescription,
          },
        },
        db,
      );
      catalogItemIds.set(product.partnerSku, item.catalogItemId as string);
    } else {
      const published = await db
        .collection(`${paths.organization(supplier.orgId)}/partnerCatalog`)
        .where('sourceProductId', '==', id)
        .limit(1)
        .get();
      const existing = published.docs[0];
      if (!existing) throw new Error(`No catalog item found for ${product.sku}`);
      catalogItemIds.set(product.partnerSku, existing.id);
    }
  }

  // ── 4 · the connection, buyer → supplier ─────────────────────────────────
  const connection = await runCommand(
    connectionRequest,
    {
      uid: procurement.uid,
      orgId: buyer.orgId,
      operationId: seedOperationId(SLOT.connectionRequest),
      payload: { supplierHandle: SUPPLIER.handle },
    },
    db,
  );
  const connectionId = connection.connectionId as string;
  await runCommand(
    connectionRespond,
    {
      uid: SUPPLIER_OWNER.uid,
      orgId: supplier.orgId,
      operationId: seedOperationId(SLOT.connectionRespond),
      payload: { connectionId, response: 'ACCEPT' },
    },
    db,
  );

  // ── 5 · the mapping: 1 PACK of CKN-B5 = 5 KG of MEAT-001 ─────────────────
  const meatProductId = productIds.get('MEAT-001');
  const chickenCatalogItemId = catalogItemIds.get('CKN-B5');
  if (!meatProductId || !chickenCatalogItemId) {
    throw new Error('The canonical mapping is missing one of its two sides');
  }
  const mapping = await runCommand(
    mappingCreate,
    {
      uid: procurement.uid,
      orgId: buyer.orgId,
      operationId: seedOperationId(SLOT.mapping),
      payload: {
        connectionId,
        buyerProductId: meatProductId,
        supplierCatalogItemId: chickenCatalogItemId,
        typedPartnerSku: 'CKN-B5',
        supplierToBuyerBaseFactorMilli: 5000,
        semanticConfirmed: true,
      },
    },
    db,
  );

  // ── 6 · Green Farm Poultry, the private supplier ─────────────────────────
  await createIfAbsent(db.doc(paths.privatePartner(buyer.orgId, GREEN_FARM_ID)), {
    partnerId: GREEN_FARM_ID,
    partnerTypes: ['SUPPLIER'],
    name: 'Green Farm Poultry',
    status: 'ACTIVE',
    ordersPlacedCount: 0,
    createdAt: CLOCK.t0,
    createdBy: procurement.uid,
    updatedAt: CLOCK.t0,
    updatedBy: procurement.uid,
  });

  return {
    buyerOrgId: buyer.orgId,
    supplierOrgId: supplier.orgId,
    buyerWarehouses: { main: buyer.warehouseId, cold: coldRoomId },
    supplierWarehouseId: supplier.warehouseId,
    productIds,
    supplierProductIds,
    connectionId,
    catalogItemIds,
    mappingId: mapping.mappingId as string,
    privatePartnerId: GREEN_FARM_ID,
    uids: {
      buyerOwner: owner.uid,
      buyerInventory: inventory.uid,
      buyerProcurement: procurement.uid,
      buyerStorekeeper: storekeeper.uid,
      supplierOwner: SUPPLIER_OWNER.uid,
    },
  };
}

