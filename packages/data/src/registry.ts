import type { QueryId } from '@stockmok/shared';
import type {
  ConverterKey,
  QueryContractRecord,
  QueryFilterDefinition,
  QueryKind,
  QueryOrderDefinition,
  QueryScope,
} from './types.js';

const param = (name: string) => ({ param: name }) as const;
const fieldParam = (name: string) => ({ fieldParam: name }) as const;
const filter = (
  field: QueryFilterDefinition['field'],
  operator: QueryFilterDefinition['operator'],
  value: QueryFilterDefinition['value'],
  optional = false,
): QueryFilterDefinition => ({ field, operator, value, ...(optional ? { optional: true } : {}) });
const order = (
  field: QueryOrderDefinition['field'],
  direction: QueryOrderDefinition['direction'],
): QueryOrderDefinition => ({ field, direction });

interface DefinitionOptions {
  readonly purpose: string;
  readonly method: string;
  readonly scope: QueryScope;
  readonly kind: QueryKind;
  readonly path: string;
  readonly converter?: ConverterKey;
  readonly filters?: readonly QueryFilterDefinition[];
  readonly order?: readonly QueryOrderDefinition[];
  readonly defaultLimit?: number;
  readonly maxLimit?: number;
  readonly cursor?: boolean;
  readonly indexes?: readonly string[];
  readonly realtime?: boolean;
  readonly aggregation?: boolean;
  readonly aggregates?: QueryContractRecord['aggregates'];
  readonly transports?: QueryContractRecord['transports'];
  readonly blocked?: boolean;
}

function definition(queryId: QueryId, options: DefinitionOptions): QueryContractRecord {
  return {
    queryId,
    purpose: options.purpose,
    repositoryMethod: options.method,
    scope: options.scope,
    kind: options.kind,
    path: options.path,
    ...(options.converter ? { converter: options.converter } : {}),
    filters: options.filters ?? [],
    order: options.order ?? [],
    ...(options.defaultLimit === undefined ? {} : { defaultLimit: options.defaultLimit }),
    ...(options.maxLimit === undefined ? {} : { maxLimit: options.maxLimit }),
    cursor: options.cursor ?? false,
    indexIds: options.indexes ?? [],
    realtime: options.realtime ?? false,
    aggregation: options.aggregation ?? false,
    ...(options.aggregates ? { aggregates: options.aggregates } : {}),
    ...(options.transports ? { transports: options.transports } : {}),
    primaryTest: `query-contracts:${queryId}`,
    status: options.blocked ? 'BLOCKED_PENDING_OWNER_RULING' : 'IMPLEMENTED',
  };
}

